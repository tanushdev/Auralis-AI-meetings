"use client";

import Link from "next/link";
import { useCallback, useEffect, useMemo, useState } from "react";
import {
  ArrowRight,
  CalendarClock,
  Clock3,
  FileText,
  Plus,
  Radio,
  Search,
  Sparkles,
  Video,
} from "lucide-react";
import { PageHeader } from "@/components/layout/PageHeader";
import { EmptyMeetings, MeetingCard, MeetingCardSkeleton } from "@/components/meetings/MeetingCard";
import { JoinMeetingForm } from "@/components/meetings/JoinMeetingForm";
import { NewMeetingDialog } from "@/components/meetings/NewMeetingDialog";
import { LocalStackHealth } from "@/components/health/LocalStackHealth";
import { Badge, Button, Card, EmptyState } from "@/components/ui";
import { api, ApiError } from "@/lib/api";
import { formatDuration, formatRelative } from "@/lib/format";
import { useAuthStore } from "@/store/authStore";
import type { HealthReport, MeetingListItem, MeetingStats } from "@/types";

interface MeetingListResponse {
  page: number;
  limit: number;
  total: number;
  pages: number;
  meetings: MeetingListItem[];
}

export default function DashboardPage() {
  const user = useAuthStore((state) => state.user);
  const [meetings, setMeetings] = useState<MeetingListItem[]>([]);
  const [total, setTotal] = useState(0);
  const [stats, setStats] = useState<MeetingStats | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [newOpen, setNewOpen] = useState(false);

  const [health, setHealth] = useState<HealthReport | null>(null);
  const [healthLoading, setHealthLoading] = useState(true);
  const [healthError, setHealthError] = useState<string | null>(null);

  const firstName = useMemo(() => user?.name.split(/\s+/)[0] ?? "there", [user]);
  const greeting = useMemo(() => {
    const hour = new Date().getHours();
    if (hour < 12) return "Good morning";
    if (hour < 18) return "Good afternoon";
    return "Good evening";
  }, []);

  const loadHealth = useCallback(async () => {
    setHealthLoading(true);
    setHealthError(null);
    try {
      setHealth(await api<HealthReport>("/api/health"));
    } catch (err) {
      setHealthError(
        err instanceof ApiError
          ? err.message
          : "Could not reach the backend health endpoint. Is the server running on port 5000?",
      );
    } finally {
      setHealthLoading(false);
    }
  }, []);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const [meetingData, statsData] = await Promise.all([
        api<MeetingListResponse>("/api/meetings?limit=6"),
        api<MeetingStats>("/api/meetings/stats"),
      ]);
      setMeetings(meetingData.meetings);
      setTotal(meetingData.total);
      setStats(statsData);
    } catch (err) {
      setError(
        err instanceof ApiError
          ? err.message
          : "Could not load your meetings. Check that the backend is running.",
      );
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
    void loadHealth();
  }, [load, loadHealth]);

  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    if (params.get("new") === "1") {
      setNewOpen(true);
      window.history.replaceState({}, "", "/dashboard");
    }
  }, []);

  const activeMeeting = meetings.find((meeting) => meeting.status === "active");
  const statCards = [
    {
      label: "Meetings",
      value: stats ? String(stats.totalMeetings) : "—",
      detail: "in your workspace",
      icon: Video,
    },
    {
      label: "Transcribed",
      value: stats ? String(stats.transcribedMeetings) : "—",
      detail: "with local speech-to-text",
      icon: Radio,
    },
    {
      label: "AI summaries",
      value: stats ? String(stats.summarizedMeetings) : "—",
      detail: "generated by Ollama",
      icon: Sparkles,
    },
    {
      label: "Total time",
      value: stats ? formatDuration(stats.totalDurationSec) : "—",
      detail: "across all meetings",
      icon: Clock3,
    },
  ];

  return (
    <div>
      <PageHeader
        eyebrow="Workspace"
        title={`${greeting}, ${firstName}`}
        description="Start a room, join with a link, or revisit transcripts and summaries from earlier meetings."
        actions={
          <>
            <Link
              href="/meetings"
              className="inline-flex h-10 items-center gap-2 rounded-xl border border-line bg-panel-raised px-4 text-sm text-ink transition-colors hover:border-brand/50"
            >
              <Search className="size-4" /> Meeting history
            </Link>
            <Button onClick={() => setNewOpen(true)}>
              <Plus className="size-4" /> New meeting
            </Button>
          </>
        }
      />

      {error ? (
        <div className="mb-5 flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-amber-500/25 bg-amber-500/10 px-4 py-3 text-sm text-amber-200">
          <span>{error}</span>
          <Button size="sm" variant="secondary" onClick={() => void load()}>
            Try again
          </Button>
        </div>
      ) : null}

      <div className="grid gap-4 lg:grid-cols-[1.65fr_1fr]">
        <section className="panel relative overflow-hidden p-5 sm:p-6">
          <div className="pointer-events-none absolute -right-16 -top-20 size-64 rounded-full bg-brand/20 blur-[90px]" />
          <div className="relative">
            <Badge tone={activeMeeting ? "success" : "brand"} dot>
              {activeMeeting ? "Active room available" : "Ready to meet"}
            </Badge>
            <h2 className="mt-4 max-w-lg text-2xl font-semibold tracking-tight sm:text-3xl">
              {activeMeeting ? (
                <>
                  <span className="text-gradient">{activeMeeting.title}</span> is still open.
                </>
              ) : (
                <>
                  A room that <span className="text-gradient">listens and remembers.</span>
                </>
              )}
            </h2>
            <p className="mt-3 max-w-xl text-sm leading-relaxed text-muted">
              {activeMeeting
                ? `${activeMeeting.participantCount} participant${
                    activeMeeting.participantCount === 1 ? "" : "s"
                  } · started ${formatRelative(activeMeeting.startedAt)}. Rejoin from this browser to keep the same media devices.`
                : "Real WebRTC audio/video, live faster-whisper transcription, and a structured summary from Ollama. Recording stays in this browser."}
            </p>

            <div className="mt-5 flex flex-wrap gap-2">
              {activeMeeting ? (
                <Link
                  href={`/meeting/${activeMeeting.roomId}`}
                  className="inline-flex h-10 items-center gap-2 rounded-xl bg-brand px-4 text-sm font-medium text-white transition-colors hover:bg-brand-soft"
                >
                  <Video className="size-4" /> Rejoin room
                  <ArrowRight className="size-3.5" />
                </Link>
              ) : (
                <Button onClick={() => setNewOpen(true)}>
                  <Plus className="size-4" /> Start a meeting
                </Button>
              )}
              <Link
                href={activeMeeting ? `/meetings/${activeMeeting._id}` : "/meetings"}
                className="inline-flex h-10 items-center gap-2 rounded-xl border border-line bg-panel-raised px-4 text-sm text-ink transition-colors hover:border-brand/50"
              >
                <CalendarClock className="size-4" /> Meeting details
              </Link>
            </div>
          </div>
        </section>

        <LocalStackHealth
          report={health}
          loading={healthLoading}
          error={healthError}
          onRefresh={() => void loadHealth()}
        />
      </div>

      <section className="mt-4 panel flex flex-col gap-4 p-4 sm:flex-row sm:items-center sm:justify-between sm:p-5">
        <div className="flex items-center gap-3">
          <span className="flex size-10 shrink-0 items-center justify-center rounded-xl bg-sky-500/10 text-sky-300">
            <ArrowRight className="size-5" />
          </span>
          <div>
            <h3 className="text-sm font-semibold">Join a meeting</h3>
            <p className="text-xs text-muted">Use an invite link or the room id from a teammate.</p>
          </div>
        </div>
        <div className="w-full sm:max-w-md">
          <JoinMeetingForm compact />
        </div>
      </section>

      <section className="mt-6 grid grid-cols-2 gap-3 lg:grid-cols-4">
        {statCards.map((stat) => (
          <Card key={stat.label} className="p-4">
            <div className="flex items-start justify-between gap-2">
              <div>
                <p className="text-[11px] uppercase tracking-wide text-muted">{stat.label}</p>
                <p className="mt-2 text-2xl font-semibold tracking-tight">{stat.value}</p>
                <p className="mt-0.5 text-[10px] text-muted">{stat.detail}</p>
              </div>
              <span className="flex size-8 items-center justify-center rounded-lg bg-brand/10 text-brand-soft">
                <stat.icon className="size-4" />
              </span>
            </div>
          </Card>
        ))}
      </section>

      <section className="mt-8">
        <div className="mb-3 flex items-end justify-between gap-3">
          <div>
            <h2 className="text-lg font-semibold tracking-tight">Recent meetings</h2>
            <p className="text-xs text-muted">
              {total > 0 ? `${total} meeting${total === 1 ? "" : "s"} in history` : "Your history appears here"}
            </p>
          </div>
          <Link href="/meetings" className="text-xs font-medium text-brand-soft hover:underline">
            View all
          </Link>
        </div>

        {loading ? (
          <div className="grid gap-3 md:grid-cols-2">
            {Array.from({ length: 4 }).map((_, index) => (
              <MeetingCardSkeleton key={index} />
            ))}
          </div>
        ) : meetings.length === 0 ? (
          <EmptyMeetings onCreate={() => setNewOpen(true)} />
        ) : (
          <div className="grid gap-3 md:grid-cols-2">
            {meetings.slice(0, 4).map((meeting) => (
              <MeetingCard key={meeting._id} meeting={meeting} />
            ))}
          </div>
        )}
      </section>

      <section className="mt-8 grid gap-3 md:grid-cols-3">
        {[
          {
            icon: Radio,
            title: "Live local transcription",
            text: "Each microphone stream is transcribed separately and attributed to its authenticated speaker.",
            href: "/transcripts",
            link: "Browse transcripts",
          },
          {
            icon: Sparkles,
            title: "Auditable AI summaries",
            text: "Ollama reads the real transcript and returns validated JSON; missing details stay null.",
            href: "/meetings",
            link: "Open summaries",
          },
          {
            icon: FileText,
            title: "Private recordings",
            text: "Recordings are mixed in the browser and stored in IndexedDB. Only metadata reaches MongoDB.",
            href: "/recordings",
            link: "Local recordings",
          },
        ].map((item) => (
          <Link
            key={item.title}
            href={item.href}
            className="panel group p-4 transition-colors hover:border-brand/40"
          >
            <span className="flex size-9 items-center justify-center rounded-xl bg-brand/10 text-brand-soft">
              <item.icon className="size-4" />
            </span>
            <h3 className="mt-3 text-sm font-semibold">{item.title}</h3>
            <p className="mt-1 text-xs leading-relaxed text-muted">{item.text}</p>
            <span className="mt-3 inline-flex items-center gap-1 text-[11px] font-medium text-brand-soft">
              {item.link}
              <ArrowRight className="size-3 transition-transform group-hover:translate-x-0.5" />
            </span>
          </Link>
        ))}
      </section>

      <NewMeetingDialog open={newOpen} onClose={() => setNewOpen(false)} />
    </div>
  );
}
