#!/usr/bin/env node
/**
 * Generates per-service env files from the single root `.env`.
 *
 * - Creates `.env` from `.env.example` when missing.
 * - Generates JWT_SECRET / TRANSCRIPTION_TOKEN when they are still placeholders.
 * - Writes backend/.env, frontend/.env.local and transcription/.env.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const root = path.resolve(import.meta.dirname, "..");
const envPath = path.join(root, ".env");
const examplePath = path.join(root, ".env.example");

if (!fs.existsSync(examplePath)) {
  console.error("Missing .env.example");
  process.exit(1);
}

if (!fs.existsSync(envPath)) {
  fs.copyFileSync(examplePath, envPath);
  console.log("Created .env from .env.example");
}

let raw = fs.readFileSync(envPath, "utf8");

const placeholder = (key) =>
  new RegExp(`^${key}=replace-with[^\\r\\n]*$`, "m").test(raw) ||
  new RegExp(`^${key}=\\s*$`, "m").test(raw);

let changed = false;
if (placeholder("JWT_SECRET")) {
  raw = raw.replace(
    /^JWT_SECRET=.*$/m,
    `JWT_SECRET=${crypto.randomBytes(48).toString("base64url")}`,
  );
  changed = true;
}
if (placeholder("TRANSCRIPTION_TOKEN")) {
  raw = raw.replace(
    /^TRANSCRIPTION_TOKEN=.*$/m,
    `TRANSCRIPTION_TOKEN=${crypto.randomBytes(32).toString("base64url")}`,
  );
  changed = true;
}
if (changed) {
  fs.writeFileSync(envPath, raw);
  console.log("Generated random local secrets in .env");
}

/** Parse simple KEY=VALUE lines, ignoring comments and blanks. */
const parse = (text) => {
  const out = new Map();
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    out.set(key, value);
  }
  return out;
};

const env = parse(raw);

const BACKEND_KEYS = [
  "PORT",
  "HOST",
  "NODE_ENV",
  "CORS_ORIGINS",
  "MONGO_URI",
  "JWT_SECRET",
  "JWT_EXPIRES_IN",
  "GUEST_TOKEN_EXPIRES_IN",
  "TRANSCRIPTION_URL",
  "TRANSCRIPTION_WS_URL",
  "TRANSCRIPTION_TOKEN",
  "TRANSCRIPTION_PROVIDER",
  "WHISPER_MODEL",
  "AI_PROVIDER",
  "OLLAMA_URL",
  "OLLAMA_MODEL",
  "OLLAMA_TIMEOUT_MS",
  "OLLAMA_NUM_CTX",
  "SUMMARY_INCREMENT_SEGMENTS",
  "SUMMARY_INCREMENT_MIN_MS",
  "SUMMARY_CHUNK_CHARS",
  "MAX_PARTICIPANTS",
  "MAX_UPLOAD_MB",
];

const FRONTEND_KEYS = [
  "NEXT_PUBLIC_API_URL",
  "NEXT_PUBLIC_WS_URL",
  "NEXT_PUBLIC_ICE_SERVERS",
];

const TRANSCRIPTION_KEYS = [
  "TRANSCRIPTION_TOKEN",
  "TRANSCRIPTION_PROVIDER",
  "WHISPER_MODEL",
  "WHISPER_DEVICE",
  "WHISPER_COMPUTE_TYPE",
  "WHISPER_LANGUAGE",
  "WHISPER_CHUNK_SECONDS",
  "WHISPER_STRIDE_SECONDS",
  "WHISPER_PROVISIONAL_INTERVAL",
  "WHISPER_MODEL_DIR",
  "WHISPER_CONCURRENCY",
  "WHISPER_PRELOAD",
];

const build = (keys, target) =>
  [
    "# Generated by `npm run setup` - edit the root .env instead",
    ...keys.map((key) => `${key}=${env.get(key) ?? ""}`),
    "",
  ].join("\n");

const write = (relative, contents) => {
  const file = path.join(root, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
  console.log(`Wrote ${relative}`);
};

write("backend/.env", build(BACKEND_KEYS));
write("frontend/.env.local", build(FRONTEND_KEYS));
write("transcription/.env", build(TRANSCRIPTION_KEYS));

console.log("\nEnvironment ready. Next steps:");
console.log("  1. Start MongoDB (already running as a service on Windows)");
console.log("  2. Start Ollama and pull the configured model");
console.log("  3. Create the Python venv: see README");
console.log("  4. npm run dev  +  npm run dev:transcription");
